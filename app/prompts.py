def _replace_tone(base: str, tone_block: str) -> str:
    """Swap the '# 말투' section of SYSTEM_PROMPT with the given tone block."""
    import re

    pattern = r"# 말투\n(?:- .*\n?)+"
    return re.sub(pattern, tone_block + "\n", base, count=1)


